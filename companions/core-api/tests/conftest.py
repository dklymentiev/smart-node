            cur.execute(
                "INSERT INTO sn_config.tenants (id, slug, name) VALUES (%s, %s, %s) "
                "ON CONFLICT (id) DO NOTHING",
                (tid, f"test-tenant-{tid}", f"Test Tenant {tid}"),
            )
