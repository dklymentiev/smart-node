-- 023_projects.sql -- a project is a row, a group and a directory.
--
-- WHY A ROW AND NOT A DIRECTORY CONVENTION. The slug is the one key across
-- memory (project-<slug>), documents (<slug>/), the node planner's project of
-- the same name and the filesystem (/srv/projects/<slug>). A convention holds
-- none of that mapping, and the projector and drift detector planned for 1.11.0
-- would have nothing to compare the disk against: a directory with no owner
-- would be indistinguishable from a correct one.
--
-- WHY FLAT. the old project layout put the owner in the path (/srv/workspaces/{dept,agent}/
-- <project>) and is superseded. A filesystem path expresses exactly ONE
-- hierarchy, so a project shared by two workspaces has no home, a change of
-- owner becomes a physical move, and the old project layout records that path on the
-- task -- so every recorded path breaks. The deciding property is
-- reversibility: flat does not foreclose workspaces (one column, nothing moves
-- on disk), nested forecloses flat (every file moves).
--
-- workspace_id is therefore present and normally NULL. That is the column.
--
-- planner_project REFERENCES the node planner's project rather than duplicating
-- it. Duplicating it breaks "one door per class" on day one.
--
-- WHAT THIS SUPERSEDES. The node already carried two empty grouping tables:
-- departments (0 rows) and teams + team_members (0 and 0). projects would make
-- a third, so the ADR says which survives -- projects replaces teams;
-- departments stays because agents.department_id references it and it is
-- already in the agent payload.
--
-- REFERENCE ONLY -- there is no migration runner on a node (docs/runbook-
-- update.md: "the database schema is baked, not migrated"). The statements that
-- actually reach a node are in bootstrap/B02-sn-core-schema.sql (fresh) and
-- bootstrap/B02-sn-core-seed.sql (installed, idempotent, applied by re-running
-- B02). This file is the written record; keep the three in step.

CREATE TABLE IF NOT EXISTS sn_config.projects (
    id integer GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    slug text NOT NULL,
    name text NOT NULL,
    unix_group text NOT NULL,
    fs_path text NOT NULL,
    workspace_id integer,
    planner_project text,
    created_by text,
    created_at timestamp with time zone DEFAULT now() NOT NULL,
    archived_at timestamp with time zone,
    tenant_id integer DEFAULT 1 NOT NULL,
    CONSTRAINT projects_slug_chk CHECK (slug ~ '^[a-z][a-z0-9-]{1,40}$')
);

CREATE TABLE IF NOT EXISTS sn_config.project_members (
    project_id integer NOT NULL,
    member_kind text NOT NULL,
    member_id text NOT NULL,
    role text DEFAULT 'member' NOT NULL,
    created_at timestamp with time zone DEFAULT now() NOT NULL,
    CONSTRAINT project_members_kind_chk CHECK (member_kind IN ('user', 'agent')),
    CONSTRAINT project_members_role_chk CHECK (role IN ('lead', 'member', 'viewer'))
);

DO $projfk$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'projects_pkey'
                     AND conrelid = 'sn_config.projects'::regclass) THEN
        ALTER TABLE sn_config.projects ADD CONSTRAINT projects_pkey PRIMARY KEY (id);
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'projects_slug_key') THEN
        ALTER TABLE sn_config.projects ADD CONSTRAINT projects_slug_key UNIQUE (slug);
    END IF;
    -- One group per project, enforced rather than assumed: two projects sharing
    -- a group means every member of one can write the other's directory.
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'projects_unix_group_key') THEN
        ALTER TABLE sn_config.projects ADD CONSTRAINT projects_unix_group_key UNIQUE (unix_group);
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'project_members_pkey'
                     AND conrelid = 'sn_config.project_members'::regclass) THEN
        ALTER TABLE sn_config.project_members
            ADD CONSTRAINT project_members_pkey PRIMARY KEY (project_id, member_kind, member_id);
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'project_members_project_id_fkey') THEN
        ALTER TABLE sn_config.project_members
            ADD CONSTRAINT project_members_project_id_fkey
            FOREIGN KEY (project_id) REFERENCES sn_config.projects(id) ON DELETE CASCADE;
    END IF;
END
$projfk$;

CREATE INDEX IF NOT EXISTS project_members_member_idx
    ON sn_config.project_members (member_kind, member_id);

COMMENT ON TABLE sn_config.projects IS
    'a project is a registry row -- slug is the one key across memory, documents, planner and /srv/projects/<slug>.';

