-- Reference migration for the session context handoff policy.
--
-- Production schema is applied by bootstrap/B02-sn-core-schema.sql and
-- B02-sn-core-seed.sql.  companions/core-api/migrations is retained as the
-- component-level schema history; core-api.sh deliberately does not run it.

CREATE TABLE IF NOT EXISTS sn_config.session_context_limits (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    scope_type text NOT NULL,
    scope_id text,
    threshold_tokens integer NOT NULL DEFAULT 120000
        CHECK (threshold_tokens BETWEEN 10000 AND 1000000),
    enabled boolean NOT NULL DEFAULT true,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT session_context_limits_scope_check CHECK (
        (scope_type = 'global' AND scope_id IS NULL)
        OR (scope_type = 'agent' AND scope_id IS NOT NULL AND length(scope_id) > 0)
    ),
    CONSTRAINT session_context_limits_scope_key
        UNIQUE NULLS NOT DISTINCT (scope_type, scope_id)
);

INSERT INTO sn_config.session_context_limits
    (scope_type, scope_id, threshold_tokens, enabled)
VALUES ('global', NULL, 120000, true)
ON CONFLICT (scope_type, scope_id) DO NOTHING;

UPDATE sn_config.cli_providers
   SET env_vars = env_vars || '{"CLAUDE_CODE_AUTO_COMPACT_WINDOW": "200000"}'::jsonb
 WHERE slug = 'claude-cli'
   AND NOT (env_vars ? 'CLAUDE_CODE_AUTO_COMPACT_WINDOW');
